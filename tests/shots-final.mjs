import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: process.env.HOME + '/Library/Caches/ms-playwright/chromium-1248/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing', args:['--use-gl=angle','--use-angle=swiftshader','--enable-webgl','--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
page.on('pageerror', e => console.log('PAGEERROR', e.message));
await page.goto('http://127.0.0.1:4173/', { waitUntil: 'networkidle' });
await page.waitForSelector('.loader', { state: 'detached', timeout: 20000 });
await page.waitForTimeout(700);
await page.screenshot({path:'screenshots/01-start.png'});
await page.getByRole('button',{name:/Start shift/}).click();
await page.waitForTimeout(1600);
await page.locator('#call-accept').click({force:true});
await page.waitForTimeout(700);
await page.screenshot({path:'screenshots/02-call.png'});
// skip to load phone for chat
await page.evaluate(()=>{ const g=window.__D2D__; g.closeModal(); g.enterStage(1); });
await page.waitForTimeout(1600);
if (await page.locator('[data-tab="chat"]').count()) await page.locator('[data-tab="chat"]').click({force:true});
await page.waitForTimeout(300);
await page.screenshot({path:'screenshots/03-chat.png'});
await page.evaluate(()=>window.__D2D__.closeModal());
await page.evaluate(()=>window.__D2D__.enterStage(4));
await page.waitForTimeout(6500);
await page.screenshot({path:'screenshots/04-coupling.png'});
await page.evaluate(()=>window.__D2D__.enterStage(5));
await page.waitForTimeout(6500);
await page.getByRole('button',{name:/Open proof camera/}).click();
await page.waitForTimeout(4500);
await page.screenshot({path:'screenshots/05-seal-camera.png'});
await page.evaluate(()=>{ window.__D2D__.closePhoto(true); window.__D2D__.enterStage(6); });
await page.waitForTimeout(2500);
await page.screenshot({path:'screenshots/06-road.png'});
await page.evaluate(()=>window.__D2D__.enterStage(8));
await page.waitForTimeout(6500);
await page.screenshot({path:'screenshots/07-pod.png'});
await page.evaluate(()=>window.__D2D__.enterStage(9));
await page.waitForTimeout(4000);
await page.screenshot({path:'screenshots/08-debrief.png'});
await browser.close();
